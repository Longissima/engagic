CREATE FUNCTION jurisdictions_type_from_kind() RETURNS trigger AS $$
BEGIN
    -- Raw inserts that only name a general class ("city") still get a kind.
    IF NEW.kind IS NULL AND NEW.type IN ('city', 'township', 'county', 'school_district', 'state') THEN
        NEW.kind := NEW.type;
    END IF;
    IF NEW.kind IS NULL THEN
        RAISE EXCEPTION 'jurisdiction % needs a kind (see jurisdiction_kinds)', NEW.banana;
    END IF;
    SELECT k.type INTO NEW.type FROM jurisdiction_kinds k WHERE k.kind = NEW.kind;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER jurisdictions_type_from_kind
    BEFORE INSERT OR UPDATE OF kind, type ON jurisdictions
    FOR EACH ROW EXECUTE FUNCTION jurisdictions_type_from_kind();

UPDATE jurisdictions j SET type = k.type FROM jurisdiction_kinds k WHERE k.kind = j.kind;

