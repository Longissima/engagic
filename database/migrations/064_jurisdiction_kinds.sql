-- Jurisdiction kind: the function a body serves, beneath a five-way class.
--
-- jurisdictions.type had grown to 60 free-text values (the onboarding prompt
-- accepted any string, and the Census sweep copied function codes verbatim).
-- type now holds the class the pipeline and coverage reports branch on: city,
-- county, school_district, special_district, state. kind holds the detail a
-- reader cares about (port, fire_district, transit) and is the only thing a
-- writer sets; a trigger copies type from the kind's registry row, so the two
-- cannot disagree. Rules for classifying new bodies live in
-- database/jurisdiction_kinds.py and may only name kinds seeded here.
--
-- The pre-migration values stay in jurisdiction_type_legacy for the rollback
-- and for auditing a reassignment.

CREATE TABLE jurisdiction_type_legacy (
    banana TEXT PRIMARY KEY,
    type TEXT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO jurisdiction_type_legacy (banana, type) SELECT banana, type FROM jurisdictions;

